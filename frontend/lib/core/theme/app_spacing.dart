/// App spacing constants following Material Design 3 spacing system.
/// All spacing values are in logical pixels (dp).
class AppSpacing {
  AppSpacing._(); // Private constructor to prevent instantiation

  // ============================================================================
  // Base Spacing Scale
  // ============================================================================

  /// Extra small spacing - 4px
  static const double xs = 4.0;

  /// Small spacing - 8px
  static const double sm = 8.0;

  /// Medium spacing - 16px
  static const double md = 16.0;

  /// Large spacing - 24px
  static const double lg = 24.0;

  /// Extra large spacing - 32px
  static const double xl = 32.0;

  /// 2x extra large spacing - 48px
  static const double xxl = 48.0;

  /// 3x extra large spacing - 64px
  static const double xxxl = 64.0;

  // ============================================================================
  // Commonly Used Spacing Values
  // ============================================================================

  /// Content padding - 16px
  static const double contentPadding = md;

  /// Component padding - 12px
  static const double componentPadding = 12.0;

  /// Button padding horizontal - 24px
  static const double buttonPaddingHorizontal = lg;

  /// Button padding vertical - 12px
  static const double buttonPaddingVertical = 12.0;

  /// Card padding - 16px
  static const double cardPadding = md;

  /// Card margin - 8px
  static const double cardMargin = sm;

  /// List item padding - 16px
  static const double listItemPadding = md;

  /// List item divider height - 1px
  static const double listItemDividerHeight = 1.0;

  /// Dialog padding - 24px
  static const double dialogPadding = lg;

  /// Dialog title bottom margin - 24px
  static const double dialogTitleMargin = lg;

  /// Screen horizontal padding - 16px
  static const double screenHorizontalPadding = md;

  /// Screen vertical padding - 24px
  static const double screenVerticalPadding = lg;

  // ============================================================================
  // Border Radius Values
  // ============================================================================

  /// Extra small border radius - 4px
  static const double borderRadiusXs = 4.0;

  /// Small border radius - 8px
  static const double borderRadiusSm = 8.0;

  /// Medium border radius - 12px
  static const double borderRadiusMd = 12.0;

  /// Large border radius - 16px
  static const double borderRadiusLg = 16.0;

  /// Extra large border radius - 28px (pill shape)
  static const double borderRadiusXl = 28.0;

  // ============================================================================
  // Icon Sizes
  // ============================================================================

  /// Extra small icon - 16px
  static const double iconXs = 16.0;

  /// Small icon - 20px
  static const double iconSm = 20.0;

  /// Medium icon - 24px
  static const double iconMd = 24.0;

  /// Large icon - 32px
  static const double iconLg = 32.0;

  /// Extra large icon - 48px
  static const double iconXl = 48.0;

  // ============================================================================
  // Avatar Sizes
  // ============================================================================

  /// Small avatar - 32px
  static const double avatarSm = 32.0;

  /// Medium avatar - 48px
  static const double avatarMd = 48.0;

  /// Large avatar - 64px
  static const double avatarLg = 64.0;

  /// Extra large avatar - 96px
  static const double avatarXl = 96.0;

  // ============================================================================
  // Input Heights
  // ============================================================================

  /// Small input field height - 32px
  static const double inputHeightSm = 32.0;

  /// Medium input field height - 40px
  static const double inputHeightMd = 40.0;

  /// Large input field height - 48px
  static const double inputHeightLg = 48.0;

  // ============================================================================
  // Button Heights
  // ============================================================================

  /// Small button height - 32px
  static const double buttonHeightSm = 32.0;

  /// Medium button height - 40px
  static const double buttonHeightMd = 40.0;

  /// Large button height - 48px
  static const double buttonHeightLg = 48.0;

